// Generates src/generated/columns.js from schema.json. Output is gitignored.
const fs = require('fs');
const path = require('path');
const schema = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'schema.json'), 'utf8'));
const out = path.join(__dirname, '..', 'src', 'generated');
fs.mkdirSync(out, { recursive: true });
const columnsByReport = Object.fromEntries(Object.entries(schema.reports).map(([name, r]) => [name, r.columns]));
const body = `// AUTO-GENERATED by scripts/codegen.js from schema.json. Do not edit.
module.exports = ${JSON.stringify(columnsByReport, null, 2)};
module.exports.SCHEMA_HASH = ${JSON.stringify(require('crypto').createHash('sha1').update(JSON.stringify(schema)).digest('hex').slice(0, 8))};
`;
fs.writeFileSync(path.join(out, 'columns.js'), body);
console.log('generated src/generated/columns.js');
